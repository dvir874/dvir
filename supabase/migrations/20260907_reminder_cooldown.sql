-- קירור מקוצר בין הזמנה לתזכורת, לאירוע אחד, במפורש.
--
-- ברירת המחדל היא חמישה ימים (REMINDER_COOLDOWN_H = 120) והיא נמדדה: תזכורת
-- שנייה שלושה ימים אחרי הראשונה מגיעה בזמן שהראשונה עדיין מתעלמת ממנה.
-- אבל המדידה ההיא היא על תזכורת שנייה. תזכורת ראשונה היא הודעה אחרת.
--
-- שלמה, 07/09: ההזמנות יצאו 3–5/09, אף אחד לא קיבל תזכורת אחת, ודביר רוצה
-- שהראשונה תצא היום ולא מחר. 145 אורחים ממתינים, 241 מקומות פנויים במכסה.
--
-- NULL = חמישה ימים כרגיל. הערך רק מקצר, לעולם לא מאריך.

ALTER TABLE events ADD COLUMN IF NOT EXISTS reminder_cooldown_h smallint;

COMMENT ON COLUMN events.reminder_cooldown_h IS
  'שעות המתנה בין הודעה לתזכורת לאירוע הזה. NULL = ברירת המחדל (120 שעות). רק מקצר.';

-- אבישג ושלמה — 24 שעות, כדי שהתזכורת הראשונה תצא היום.
UPDATE events SET reminder_cooldown_h = 24
WHERE id = '7e1a56b5-1083-4afd-8317-9cd52557534d';
