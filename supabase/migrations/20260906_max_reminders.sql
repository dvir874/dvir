-- NULL = הכלל הרגיל, שלוש.

ALTER TABLE events ADD COLUMN IF NOT EXISTS max_reminders smallint;

COMMENT ON COLUMN events.max_reminders IS
  'תקרת תזכורות לאירוע הזה. NULL = ברירת המחדל (3). נקבע רק לבקשת הזוג.';

-- תהל ואביב — 86 אורחים מיצו שלוש. רביעית, ואחרונה.
UPDATE events SET max_reminders = 4
