-- תפריט במקום שורת פקודה, ותשובה לאורח רק אחרי בחירה מפורשת.
--
-- הקונסולה נבנתה כך שכל מה שהיא לא מזהה נשלח לאורח שעליו הייתה ההתראה
-- האחרונה. זה נכון ל"היי נעם, מה קרה?" והרסני ל"כמה אישרו" — והרצה של
-- הפרסר האמיתי מראה שחמישה מתוך שבעה ניסוחים סבירים של דביר נשלחים לאורח
-- מילה במילה. אחד מהם באמת יצא, ב-08/09 ב-07:24, לאורחת שיום קודם כתבה
-- "אל תחזרו"; הוא נכשל רק כי חלון 24 השעות של מטא נסגר 75 דקות קודם.
--
-- רשימת חסימות לא פותרת את זה. ניסינו ב-08/09 ב-00:54, ו"איזה אורחים לא
-- יודעי" הגיע שש וחצי שעות אחר כך. אי אפשר למנות מה מישהו יקליד; אפשר
-- למנות מה הוא יכול ללחוץ.
--
-- mode הוא הנעילה: טקסט חופשי מגיע לאורח רק כאשר mode='reply', כלומר רק
-- אחרי שדביר בחר במפורש "לענות לאורח" ולחץ על השם שלו. mode_at מפקיע את
-- הבחירה, כדי שכוונה מלפני שעתיים לא תיישם את עצמה על משפט אקראי.
--
-- לפני שהמיגרציה רצה העמודות חסרות, mode נקרא כ-undefined, וטקסט חופשי
-- פותח תפריט במקום להישלח. כלומר פריסה לפני הרצה הופכת את הקונסולה
-- לבטוחה יותר, לא לשבורה.

ALTER TABLE admin_context ADD COLUMN IF NOT EXISTS mode    text;
ALTER TABLE admin_context ADD COLUMN IF NOT EXISTS mode_at timestamptz;

COMMENT ON COLUMN admin_context.mode    IS '''reply'' = ההודעה הבאה מדביר נשלחת לאורח. NULL = טקסט חופשי פותח תפריט';
COMMENT ON COLUMN admin_context.mode_at IS 'מתי נבחר המצב — פוקע אחרי 30 דקות';
