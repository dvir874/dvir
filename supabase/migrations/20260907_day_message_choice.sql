-- הודעה אחת ליד החתונה, לא שתיים.
--
-- "מחר מתחתנים" יוצאת בערב שלפני, "היום מתחתנים" בבוקר עצמו. שתיהן נבנו, ואורח
-- שמקבל את שתיהן מקבל את אותם ארבעה פרטים פעמיים תוך שמונה־עשרה שעות.
--
-- דביר, 06/09: "עדיף שתצא הודעה אחת - או היום זה קורה או מחר זה קורה".
-- זו בחירה של הזוג, לכל חתונה בנפרד: חתונה שרוב האורחים נוסעים אליה שעה רוצה
-- את הערב שלפני, וחתונה שכולם מקומיים רוצה את הבוקר.
--
-- NULL = ההתנהגות הקיימת (ערב לפני), אז אף חתונה קיימת לא משנה התנהגות.

ALTER TABLE events ADD COLUMN IF NOT EXISTS day_message text;

COMMENT ON COLUMN events.day_message IS
  'איזו הודעה יוצאת ליד החתונה: NULL/before = ערב לפני, day_of = בוקר החתונה. תמיד אחת בלבד.';

